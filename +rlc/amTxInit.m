function tx = amTxInit(cfg)
%amTxInit Establish the transmitting side of an AM RLC entity.
%Spec:   TS 38.322 V16.3.0, clause 5.1.1; clause 7.1 transmit-side state variables
%        (TX_Next_Ack, TX_Next, POLL_SN, all "initially set to 0") and counters
%        (PDU_WITHOUT_POLL, BYTE_WITHOUT_POLL "initially set to 0"; RETX_COUNT, "one RETX_COUNT
%        counter maintained per RLC SDU"); clause 7.3 t-PollRetransmit. Re-establishment
%        (clause 5.1.2) is a fresh call.
%Inputs: cfg  struct from rlc.amConfig
%Outputs: tx  scalar struct, all state explicit:
%            .cfg                    configuration
%            .TX_Next_Ack .TX_Next .POLL_SN          integers -- clause 7.1, verbatim
%            .PDU_WITHOUT_POLL .BYTE_WITHOUT_POLL    integers -- clause 7.1 counters
%            .tPollRetransmitExpiry  ms, -1 when not running
%            .pollPending            logical -- t-PollRetransmit expired and clause 5.3.3.4's
%                                    "include a poll in an AMD PDU" is owed to the next PDU
%            .highestSubmittedSn     integer, -1 before anything is submitted -- "the highest
%                                    SN of the AMD PDU among the AMD PDUs submitted to lower
%                                    layer" (clauses 5.3.2 and 5.3.3.2)
%          One entry per SDU not yet positively acknowledged, in SN order:
%            .sduSn      1 x N integer -- SN, bound at arrival (see amTxEnqueue)
%            .sduLen     1 x N integer, bytes
%            .sduTag     1 x N integer -- caller's identifier, returned on acknowledgement
%            .sduSent    1 x N integer -- bytes submitted as NEW data so far
%            .RETX_COUNT 1 x N integer -- clause 7.1 c); -1 until first considered for
%                        retransmission, which is when clause 5.3.2 sets it to zero
%            .buf        1 x sum(sduLen) octets -- the SDUs, kept until acknowledged because
%                        a retransmission re-reads them
%          The retransmission buffer, one entry per byte range pending retransmission:
%            .retxSn .retxSo .retxEnd  1 x R integers -- SN and inclusive byte range

if ~isstruct(cfg) || ~isfield(cfg, 'mode') || ~strcmp(cfg.mode, 'am')
    error('rlc:amTxInit:badCfg', 'amTxInit: cfg must come from rlc.amConfig');
end
tx = struct( ...
    'cfg',                   cfg, ...
    'TX_Next_Ack',           0, ...
    'TX_Next',               0, ...
    'POLL_SN',               0, ...
    'PDU_WITHOUT_POLL',      0, ...
    'BYTE_WITHOUT_POLL',     0, ...
    'tPollRetransmitExpiry', -1, ...
    'pollPending',           false, ...
    'highestSubmittedSn',    -1, ...
    'sduSn',                 zeros(1, 0), ...
    'sduLen',                zeros(1, 0), ...
    'sduTag',                zeros(1, 0), ...
    'sduSent',               zeros(1, 0), ...
    'RETX_COUNT',            zeros(1, 0), ...
    'buf',                   zeros(1, 0), ...
    'retxSn',                zeros(1, 0), ...
    'retxSo',                zeros(1, 0), ...
    'retxEnd',               zeros(1, 0));
end
